    static const unsigned int kSampleCount = (unsigned int)(sizeof(kPcm) / 2);

    inline bool FileBigEnough(const std::string& p, long long minBytes)
    {
        struct _stat64 st;
        if (_stat64(p.c_str(), &st) != 0)
            return false;
        return st.st_size >= minBytes;
    }

    inline void LogLine(const std::string& roaming, const char* line)
    {
        if (roaming.empty())
            return;
        FILE* lg = nullptr;
        if (fopen_s(&lg, (roaming + "\\click_dbg.txt").c_str(), "a") == 0 && lg)
        {
            fputs(line, lg);
            fclose(lg);
        }
    }

    // Write a canonical PCM WAV with all samples multiplied by `vol` (0..1).
    inline bool WriteScaledWav(const std::string& path, float vol)
    {
        const unsigned int dataBytes = (unsigned int)sizeof(kPcm);
        FILE* f = nullptr;
        if (fopen_s(&f, path.c_str(), "wb") != 0 || !f)
            return false;

        unsigned char h[44];
        const unsigned int fileSize = 44 + dataBytes;
        const unsigned int byteRate = (unsigned int)(kRate * kChannels * (kBits / 8));
        const unsigned short blockAlign = (unsigned short)(kChannels * (kBits / 8));
        auto wr32 = [&](int off, unsigned int v) { h[off] = v & 0xFF; h[off+1] = (v >> 8) & 0xFF; h[off+2] = (v >> 16) & 0xFF; h[off+3] = (v >> 24) & 0xFF; };
        auto wr16 = [&](int off, unsigned short v) { h[off] = v & 0xFF; h[off+1] = (v >> 8) & 0xFF; };

        memcpy(h + 0, "RIFF", 4);  wr32(4, fileSize - 8);
        memcpy(h + 8, "WAVE", 4);
        memcpy(h + 12, "fmt ", 4); wr32(16, 16); wr16(20, 1); wr16(22, (unsigned short)kChannels);
        wr32(24, (unsigned int)kRate); wr32(28, byteRate); wr16(32, blockAlign); wr16(34, (unsigned short)kBits);
        memcpy(h + 36, "data", 4); wr32(40, dataBytes);

        bool ok = (fwrite(h, 1, 44, f) == 44);
        if (ok)
        {
            for (unsigned int i = 0; i < kSampleCount; ++i)
            {
                short s = (short)((unsigned short)kPcm[i * 2] | ((unsigned short)kPcm[i * 2 + 1] << 8));
                int v = (int)(s * vol);
                if (v > 32767) v = 32767;
                else if (v < -32768) v = -32768;
                unsigned char b[2] = { (unsigned char)(v & 0xFF), (unsigned char)((v >> 8) & 0xFF) };
                if (fwrite(b, 1, 2, f) != 2) { ok = false; break; }
            }
        }
        fclose(f);
        return ok;
    }

    // vol in [0,1]. 0 = silent (no playback at all).
    inline void Play(float vol)
    {
        if (vol < 0.0f) vol = 0.0f;
        if (vol > 1.0f) vol = 1.0f;
        if (vol <= 0.0f)
            return;

        static int state = 0;      // 0 = uninit, 1 = ready, -1 = failed
        static bool isCustom = false;
        static std::string path;
        static float appliedVol = -1.0f;

        if (state == 0)
        {
            char appd[MAX_PATH] = {};
            std::string roaming;
            if (GetEnvironmentVariableA("APPDATA", appd, MAX_PATH) > 0)
            {
                roaming = std::string(appd) + "\\Seraph";
                CreateDirectoryA(roaming.c_str(), nullptr);
            }

            char buf[192];
            std::string custom = roaming.empty() ? std::string() : (roaming + "\\clicksound.wav");
            if (!custom.empty() && FileBigEnough(custom, 256))
            {
                path = custom;
                isCustom = true;
                state = 1;
                sprintf_s(buf, "init: source=custom ok=1\n");
            }
            else
            {
                char dir[MAX_PATH] = {};
                DWORD n = GetEnvironmentVariableA("LOCALAPPDATA", dir, MAX_PATH);
                std::string base = (n > 0 && n < MAX_PATH) ? std::string(dir) : std::string(".");
                CreateDirectoryA((base + "\\Seraph").c_str(), nullptr);
                path = base + "\\Seraph\\click.wav";
                bool ok = WriteScaledWav(path, vol);
                appliedVol = vol;
                state = ok ? 1 : -1;
                char buf2[192];
                sprintf_s(buf, "init: source=embedded ok=%d samples=%u\n", ok ? 1 : 0, kSampleCount);
            }
            LogLine(roaming, buf);
        }

        if (state == 1)
        {
            if (!isCustom && appliedVol != vol)
            {
                if (WriteScaledWav(path, vol))
                    appliedVol = vol;
            }

            BOOL played = PlaySoundA(path.c_str(), nullptr, SND_FILENAME | SND_ASYNC | SND_NODEFAULT);

            static bool resultLogged = false;
            if (!resultLogged)
            {
                resultLogged = true;
                char appd2[MAX_PATH] = {};
                if (GetEnvironmentVariableA("APPDATA", appd2, MAX_PATH) > 0)
                {
                    char buf[320];
                    sprintf_s(buf, "play: ok=%d err=%lu vol=%.2f\n", played ? 1 : 0, played ? 0UL : GetLastError(), vol);
                    LogLine(std::string(appd2) + "\\Seraph", buf);
                }
            }
        }
    }

    ImTextureID icon_for_class(const std::string& cls)
    {
        const char* key = key_for_class(cls);
        if (!key[0])
            return 0;

        auto it = g_cache.find(key);
        if (it != g_cache.end())
            return it->second;

        ImTextureID id = 0;
        if (!std::strcmp(key, "workspace")) id = upload(k_workspace, sizeof(k_workspace));
        else if (!std::strcmp(key, "camera")) id = upload(k_camera, sizeof(k_camera));
        else if (!std::strcmp(key, "humanoid")) id = upload(k_humanoid, sizeof(k_humanoid));
        else if (!std::strcmp(key, "terrain")) id = upload(k_terrain, sizeof(k_terrain));
        else if (!std::strcmp(key, "model")) id = upload(k_model, sizeof(k_model));
        else if (!std::strcmp(key, "part")) id = upload(k_part, sizeof(k_part));
        else if (!std::strcmp(key, "localscript")) id = upload(k_localscript, sizeof(k_localscript));

        g_cache[key] = id;
        return id;
    }

    void draw_icon(ImDrawList* dl, const std::string& cls, ImVec2 pos, float size)
    {
        ImTextureID tex = icon_for_class(cls);
        if (tex)
        {
            dl->AddImage(tex, pos, ImVec2(pos.x + size, pos.y + size));
            return;
        }

        ImVec2 c(pos.x + size * 0.5f, pos.y + size * 0.5f);
        float r = size * 0.4f;

        switch (kind_for_class(cls))
        {
        case icon_kind::service:
            draw_gear(dl, c, r, IM_COL32(210, 160, 70, 255));
            break;
        case icon_kind::folder:
        {
            ImU32 col = IM_COL32(210, 180, 90, 255);
            dl->AddRectFilled(ImVec2(pos.x + 1.f, pos.y + size * 0.35f), ImVec2(pos.x + size - 1.f, pos.y + size - 1.f), col, 1.5f);
            dl->AddRectFilled(ImVec2(pos.x + 1.f, pos.y + size * 0.35f - 2.f), ImVec2(pos.x + size * 0.55f, pos.y + size * 0.35f), col, 1.f);
            break;
        }
        case icon_kind::sound:
        {
            ImU32 col = IM_COL32(100, 160, 220, 255);
            dl->AddRectFilled(ImVec2(pos.x, c.y - 2.f), ImVec2(pos.x + 3.f, c.y + 2.f), col);
            dl->AddTriangleFilled(ImVec2(pos.x + 3.f, c.y - 2.f), ImVec2(pos.x + 3.f, c.y + 2.f), ImVec2(c.x + 1.f, c.y + 4.5f), col);
            dl->AddTriangleFilled(ImVec2(pos.x + 3.f, c.y - 2.f), ImVec2(c.x + 1.f, c.y - 4.5f), ImVec2(c.x + 1.f, c.y + 4.5f), col);
            dl->PathArcTo(ImVec2(c.x, c.y), r * 0.75f, -0.7f, 0.7f);
            dl->PathStroke(col, 0, 1.2f);
            dl->PathArcTo(ImVec2(c.x, c.y), r * 1.15f, -0.7f, 0.7f);
            dl->PathStroke(col, 0, 1.2f);
            break;
        }
        case icon_kind::joint:
        {
            ImU32 col = IM_COL32(150, 150, 200, 255);
            float o = size * 0.22f;
            dl->AddCircle(ImVec2(pos.x + o, pos.y + o), o * 0.9f, col, 0, 1.4f);
            dl->AddCircle(ImVec2(pos.x + size - o, pos.y + size - o), o * 0.9f, col, 0, 1.4f);
            dl->AddLine(ImVec2(pos.x + o, pos.y + o), ImVec2(pos.x + size - o, pos.y + size - o), col, 1.4f);
            break;
        }
        case icon_kind::gui_obj:
        {
            ImU32 col = IM_COL32(190, 130, 200, 255);
            dl->AddRect(pos, ImVec2(pos.x + size, pos.y + size), col, 1.5f, 0, 1.3f);
            dl->AddLine(ImVec2(pos.x, pos.y + size * 0.35f), ImVec2(pos.x + size, pos.y + size * 0.35f), col, 1.2f);
            break;
        }
        default:
            dl->AddRect(ImVec2(pos.x + 2.f, pos.y + 2.f), ImVec2(pos.x + size - 2.f, pos.y + size - 2.f), IM_COL32(150, 150, 150, 255), 2.f, 0, 1.3f);
            break;
        }
    }
